function sym(name, grid){
  const rows=grid.trim().split('\n'); const h=rows.length;
  const w=Math.max(...rows.map(r=>r.length));
  let r='';
  rows.forEach((row,y)=>{for(let x=0;x<row.length;x++) if(row[x]==='#') r+=`<rect x="${x}" y="${y}" width="1" height="1"/>`;});
  return `<symbol id="i-${name}" viewBox="0 0 ${w} ${h}" fill="currentColor">${r}</symbol>`;
}
const sprite=`<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">`+
  Object.entries(ICONS).map(([n,g])=>sym(n,g)).join('')+`</svg>`;
writeFileSync('/tmp/sprite2.html',sprite);
